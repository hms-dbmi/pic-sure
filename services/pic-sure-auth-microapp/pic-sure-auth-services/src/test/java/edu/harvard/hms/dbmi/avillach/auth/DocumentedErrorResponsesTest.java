        privilege.setApplication(application);
        privilege = privilegeRepository.save(privilege);
        role("ROLE_HOLDING_APP_PRIVILEGE", privilege);

        mockMvc.perform(asSuperAdmin(HttpMethod.DELETE, "/application/{id}", application.getUuid())).andExpect(status().isConflict())
            .andExpect(jsonPath("$.message").value("Cannot delete this resource as it's referenced by other entities in the system"));
