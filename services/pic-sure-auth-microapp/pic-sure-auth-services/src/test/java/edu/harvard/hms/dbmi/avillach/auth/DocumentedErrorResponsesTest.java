    SessionService sessionService;

    String superAdminToken;

    /** Stands in for FENCE's OAuth token endpoint, which answers an unusable authorization code with 400 {@code invalid_grant}. */
    static HttpServer startFence() {
        try {
            HttpServer server = HttpServer.create(new InetSocketAddress("localhost", 0), 0);
            server.createContext("/user/oauth2/token", exchange -> respond(exchange, 400, "{\"error\":\"invalid_grant\"}"));
            server.start();
            return server;
        } catch (IOException e) {
            throw new IllegalStateException("Cannot start the FENCE stub", e);
        }
    }

    static void respond(HttpExchange exchange, int status, String body) throws IOException {
        byte[] bytes = body.getBytes(StandardCharsets.UTF_8);
        exchange.getResponseHeaders().add(HttpHeaders.CONTENT_TYPE, MediaType.APPLICATION_JSON_VALUE);
        exchange.sendResponseHeaders(status, bytes.length);
        try (OutputStream out = exchange.getResponseBody()) {
            out.write(bytes);
        }
    }

    @AfterAll
    static void stopFence() {
        FENCE.stop(0);
    }

    @DynamicPropertySource
    static void fenceProps(DynamicPropertyRegistry registry) {
        registry.add("fence.idp.provider.uri", () -> "http://localhost:" + FENCE.getAddress().getPort());
    }

    @BeforeEach
    void signInSuperAdmin() {
        if (userRepository.findBySubject(SUPER_ADMIN_SUBJECT) == null) {
            Privilege superAdmin = privilegeRepository.findByName(AuthNaming.AuthRoleNaming.SUPER_ADMIN);
            if (superAdmin == null) {
                superAdmin = privilege(AuthNaming.AuthRoleNaming.SUPER_ADMIN);
            }
            userWithRole(SUPER_ADMIN_SUBJECT, role("SUPER_ADMIN_ROLE", superAdmin));
        }
        String sessionId = UUID.randomUUID().toString();
        sessionService.startSession(SUPER_ADMIN_SUBJECT, sessionId);
        superAdminToken = jwtUtil.createJwtToken(null, null, new HashMap<>(Map.of("sid", sessionId)), SUPER_ADMIN_SUBJECT, 60_000L);
    }

    @Test
    void unknownAccessRuleIs404() throws Exception {
        mockMvc.perform(asSuperAdmin(HttpMethod.GET, "/accessRule/{id}", UUID.randomUUID())).andExpect(status().isNotFound())
            .andExpect(jsonPath("$.message").value("AccessRule not found"));
    }

    @Test
    void creatingNoAccessRulesIs400() throws Exception {
        mockMvc.perform(asSuperAdmin(HttpMethod.POST, "/accessRule").contentType(MediaType.APPLICATION_JSON).content("[]"))
            .andExpect(status().isBadRequest()).andExpect(jsonPath("$.message").value("No access rules added"));
    }

    @Test
    void deletingAnAccessRuleAPrivilegeStillHoldsIs409() throws Exception {
        AccessRule rule = accessRule("AR_HELD_" + UUID.randomUUID());
        Privilege holder = privilege("PRIV_HOLDING_RULE_" + UUID.randomUUID());
        holder.setAccessRules(new HashSet<>(Set.of(rule)));
        privilegeRepository.save(holder);

        mockMvc.perform(asSuperAdmin(HttpMethod.DELETE, "/accessRule/{id}", rule.getUuid())).andExpect(status().isConflict())
            .andExpect(jsonPath("$.message").value("Cannot delete this resource as it's referenced by other entities in the system"));
    }

    @Test
    void deletingAnAccessRuleAnotherRuleUsesAsAGateIs409() throws Exception {
        AccessRule gate = accessRule("AR_GATE_" + UUID.randomUUID());
        AccessRule gated = new AccessRule();
        gated.setName("AR_GATED_" + UUID.randomUUID());
        gated.setType(AccessRule.TypeNaming.ALL_EQUALS);
        gated.setGates(new HashSet<>(Set.of(gate)));
        accessRuleRepository.save(gated);

        mockMvc.perform(asSuperAdmin(HttpMethod.DELETE, "/accessRule/{id}", gate.getUuid())).andExpect(status().isConflict())
            .andExpect(jsonPath("$.message").value("Cannot delete this resource as it's referenced by other entities in the system"));
    }

